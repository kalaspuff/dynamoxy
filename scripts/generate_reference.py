"""Regenerates the reference docs that are derived from code (``docs/reference/events.md``).

    uv run python scripts/generate_reference.py

``scripts/check_consistency.py`` fails CI when the files are out of date.
"""

from __future__ import annotations

from pathlib import Path

from dynamoxy import _core
from dynamoxy.events import PYTHON_EVENT_KINDS

ROOT = Path(__file__).resolve().parents[1]
EVENTS = ROOT / "docs" / "reference" / "events.md"


def render_events() -> str:
    """The events reference: every kind with its logger, default level and description."""
    rows = [(name, level, description) for name, level, description in _core.event_kinds()]
    rows += [(kind.value, level, description) for kind, (level, description) in PYTHON_EVENT_KINDS.items()]
    lines = [
        "# Events",
        "",
        "<!-- Generated by scripts/generate_reference.py from crates/dynamoxy-core/src/events.rs and",
        "     python/dynamoxy/events.py. Do not edit. -->",
        "",
        "Every event is logged to the `dynamoxy.<category>` logger (the part of the kind before the dot)",
        "at its default level, and delivered to hooks registered with `client.on(pattern, hook)`.",
        "Log records carry the event as `record.dynamoxy`. Change levels or disable kinds with",
        "`dynamoxy.LoggingConfig`. `dynamoxy events` prints this list for the installed version.",
        "",
        "| Kind | Logger | Default level | Emitted by | Description |",
        "| --- | --- | --- | --- | --- |",
    ]
    native = {name for name, _, _ in _core.event_kinds()}
    for name, level, description in rows:
        source = "core" if name in native else "Python"
        lines.append(f"| `{name}` | `dynamoxy.{name.split('.', 1)[0]}` | {level} | {source} | {description} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    EVENTS.write_text(render_events(), encoding="utf-8")
    print(f"wrote {EVENTS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
